`ifndef CBB_GRAY2BIN_V
`define CBB_GRAY2BIN_V
module CBB_GRAY2BIN
 #(
  parameter DATA_WIDTH                          = 8                           // 数据通路位宽（>=1）
  )
  (
   input           [DATA_WIDTH-1:0]              gray_i,                       // 格雷码编码输入
   output reg      [DATA_WIDTH-1:0]              bin_o                         // 二进制解码输出
  );

// ---------------------------------------------------------------------------------------------------------------------
// 常数参数
// ---------------------------------------------------------------------------------------------------------------------

// ---------------------------------------------------------------------------------------------------------------------
// 内部信号结构
// ---------------------------------------------------------------------------------------------------------------------

// ---------------------------------------------------------------------------------------------------------------------
// 主要逻辑：格雷码转二进制码转换（MSB→LSB 逐位计算）
//   bin[N-1] = gray[N-1]                        （MSB 直通）
//   bin[i]   = gray[i] ^ bin[i+1]  (i=N-2..0)   （当前位异或高位二进制位）
//   注意：与 bin2gray 不同，gray2bin 存在串行依赖 — bin[i] 依赖 bin[i+1]。
//         从 MSB 向 LSB 逐位计算，综合为 (N-1) 级 XOR 门级联。
// ---------------------------------------------------------------------------------------------------------------------
always @*
begin : GRAY2BIN_PROC
  integer i;
  bin_o[DATA_WIDTH-1] = gray_i[DATA_WIDTH-1];
  for (i = DATA_WIDTH - 2; i >= 0; i = i - 1)
  begin
    bin_o[i] = gray_i[i] ^ bin_o[i + 1];
  end
end

// ---------------------------------------------------------------------------------------------------------------------
// 模块结束
// ---------------------------------------------------------------------------------------------------------------------
endmodule
`endif
