// Description  : 二进制码转格雷码编码器（纯组合逻辑）
//                将二进制编码转换为格雷码编码，连续二进制数对应的格雷码仅一位不同。
//                输入位宽可参数化配置，输出位宽与输入位宽相同。
//                综合工具可自动推断映射。
//                适用于跨时钟域指针、编码转换、降低开关功耗。
// ======================================================================================================================

`ifndef CBB_BIN2GRAY_V
`define CBB_BIN2GRAY_V
module CBB_BIN2GRAY
  #(
   parameter DATA_WIDTH                          = 8                           // 数据通路位宽（>=1）
   )
   (
   input wire      [DATA_WIDTH-1:0]              bin_i,                        // 二进制编码输入
   output wire     [DATA_WIDTH-1:0]              gray_o                        // 格雷码编码输出
   );

// ----------------------------------------------------------------------------------------------------------------------
// 主要逻辑：二进制转格雷码转换
//   gray[N-1] = bin[N-1]                      （MSB 直通）
//   gray[i]   = bin[i] ^ bin[i+1]  (i=0..N-2) （当前位异或相邻高位）
//   向量形式：gray = bin ^ (bin >> 1)
// 纯组合编码器不包含时钟、复位或寄存器；跨时钟域使用时，应在源时钟域寄存编码结果后再同步。
// ----------------------------------------------------------------------------------------------------------------------
assign gray_o           = bin_i ^ (bin_i >> 1'b1);

// ----------------------------------------------------------------------------------------------------------------------
// Assertions
// ----------------------------------------------------------------------------------------------------------------------
`ifdef SOC_ASSERT_ON
  `ifdef CBB_BIN2GRAY_ASSERT_ON
    `include "cbb_bin2gray_assert.sv"
  `endif
`endif

// ----------------------------------------------------------------------------------------------------------------------
// 模块结束
// ----------------------------------------------------------------------------------------------------------------------
endmodule
`endif
